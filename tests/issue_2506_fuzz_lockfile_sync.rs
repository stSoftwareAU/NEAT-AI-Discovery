#[test]
fn quality_gate_syncs_then_checks_the_fuzz_lockfile() {
    let tmp = tempfile::tempdir().expect("temp dir");
    let root = tmp.path().join("root");
    fixture(&root, "9.9.9", "1.0.0");
    copy_quality_gate(&root);
    let bin = tmp.path().join("bin");
    fs::create_dir_all(&bin).expect("create stub bin dir");
    let log = tmp.path().join("cargo-invocations.log");

    // Stub `cargo`: record the sub-command line, succeed, mutate nothing.
    write_stub(
        &bin,
        "cargo",
        &format!(
            "#!/bin/bash\nprintf '%s\\n' \"$*\" >> '{}'\nexit 0\n",
            log.display()
        ),
    );
    write_stub(&bin, "cargo-upgrade", "#!/bin/bash\nexit 0\n");
    write_stub(&bin, "shellcheck", "#!/bin/bash\nexit 0\n");
    write_stub(
        &bin,
        "mktemp",
        "#!/bin/bash\nif [ $# -eq 0 ]; then set -- \"$TMPDIR/tmp.XXXXXXXX\"; fi\nexec /usr/bin/mktemp \"$@\"\n",
    );

    // HOME points at the temp dir so quality.sh does not source the real
    // ~/.cargo/env and prepend the real cargo ahead of our stub.
    let output = Command::new("bash")
        .arg("quality.sh")
        .current_dir(&root)
        .env("PATH", format!("{}:/usr/bin:/bin", bin.display()))
        .env("HOME", tmp.path())
        .env("TMPDIR", tmp.path())
        .stdin(Stdio::null())
        .output()
        .expect("run quality.sh");

    assert!(
        output.status.success(),
        "quality.sh failed under stubbed cargo (Issue #2506)\nstdout:\n{}\nstderr:\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );

    let invocations = fs::read_to_string(&log).expect("cargo stub was never invoked");
    let lines: Vec<&str> = invocations.lines().collect();

    let metadata = lines
        .iter()
        .position(|line| {
            line.starts_with("metadata")
                && line.contains("--locked")
                && line.contains("fuzz/Cargo.toml")
        })
        .unwrap_or_else(|| {
            panic!(
                "quality.sh must run `cargo metadata --locked` on fuzz/Cargo.toml (Issue #2506) \
                 — recorded cargo calls:\n{invocations}"
            )
        });
    let deny = lines
        .iter()
        .position(|line| line.starts_with("deny"))
        .unwrap_or_else(|| {
            panic!("quality.sh must still run `cargo deny` — recorded:\n{invocations}")
        });
    assert!(
        metadata < deny,
        "the fuzz lockfile check must run before `cargo deny` (Issue #2506) — recorded:\n{invocations}"
    );
}

/// Copy `scripts/fuzz-ci.sh` and `quality/fuzz_lockfile.sh` into a temp root that
/// has a stale fuzz lock, then run the copied `fuzz-ci.sh` under stub `cargo` and
/// `rustup`. Returns the temp dir, the root and the stub's invocation log.
fn run_fuzz_ci_in_stale_root() -> (tempfile::TempDir, PathBuf, String, Output) {
    let tmp = tempfile::tempdir().expect("temp dir");
    let root = tmp.path().join("root");
    fixture(&root, "9.9.9", "1.0.0");
    let repo = Path::new(env!("CARGO_MANIFEST_DIR"));
    for rel in ["scripts/fuzz-ci.sh", "quality/fuzz_lockfile.sh"] {
        let dest = root.join(rel);
        fs::create_dir_all(dest.parent().expect("parent")).expect("create script dir");
        fs::copy(repo.join(rel), &dest).expect("copy script");
    }

    let bin = tmp.path().join("bin");
    fs::create_dir_all(&bin).expect("create stub bin dir");
    let log = tmp.path().join("cargo-invocations.log");
    write_stub(
        &bin,
        "cargo",
        &format!(
            "#!/bin/bash\nprintf '%s\\n' \"$*\" >> '{}'\nexit 0\n",
            log.display()
        ),
    );
    write_stub(&bin, "rustup", "#!/bin/bash\nexit 0\n");
    write_stub(
        &bin,
        "mktemp",
        "#!/bin/bash\nif [ $# -eq 0 ]; then set -- \"$TMPDIR/tmp.XXXXXXXX\"; fi\nexec /usr/bin/mktemp \"$@\"\n",
    );

    let output = Command::new("bash")
        .arg(root.join("scripts/fuzz-ci.sh"))
        .arg("1")
        .current_dir(&root)
        .env("PATH", format!("{}:/usr/bin:/bin", bin.display()))
        .env("TMPDIR", tmp.path())
        .stdin(Stdio::null())
        .output()
        .expect("run fuzz-ci.sh");
    let invocations = fs::read_to_string(&log).unwrap_or_default();
    (tmp, root, invocations, output)
}

#[test]
fn fuzz_ci_restamps_a_stale_lock_and_checks_it_before_fuzzing() {
    let (_tmp, root, invocations, output) = run_fuzz_ci_in_stale_root();
    assert!(
        output.status.success(),
        "fuzz-ci.sh failed (Issue #2506)\nstdout:\n{}\nstderr:\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );

    // The stale lock must now record the Cargo.toml version.
    assert_eq!(
        read_lock(&root),
        lock_text("9.9.9"),
        "fuzz-ci.sh must restamp fuzz/Cargo.lock before fuzzing (Issue #2506)"
    );

    let lines: Vec<&str> = invocations.lines().collect();
    let metadata = lines
        .iter()
        .position(|line| {
            line.starts_with("metadata")
                && line.contains("--locked")
                && line.contains("fuzz/Cargo.toml")
        })
        .unwrap_or_else(|| panic!("no `cargo metadata --locked` check recorded:\n{invocations}"));
    let first_fuzz_run = lines
        .iter()
        .position(|line| line.contains("fuzz run --locked"))
        .unwrap_or_else(|| panic!("no `fuzz run --locked` recorded:\n{invocations}"));
    assert!(
        metadata < first_fuzz_run,
        "the lock check must run before the first fuzz run (Issue #2506):\n{invocations}"
    );
}

#[test]
fn documented_fuzz_workflow_syncs_the_lock_before_its_locked_runs() {
    let text = fs::read_to_string(
        Path::new(env!("CARGO_MANIFEST_DIR")).join("docs/ci-fuzzing-workflow.yml"),
    )
    .expect("read docs/ci-fuzzing-workflow.yml");
    let step = text
        .find("- name: Sync fuzz/Cargo.lock version")
        .expect("workflow must contain the lockfile step (Issue #2506)");
    let first_run = text
        .find("cargo +nightly fuzz run --locked")
        .expect("workflow must run the fuzz targets");
    assert!(
        step < first_run,
        "the sync step must precede the first `fuzz run --locked` (Issue #2506)"
    );

    let block = text[step..]
        .split_once("      run: |\n")
        .expect("lockfile step must have a run block")
        .1;
    let commands: Vec<&str> = block
        .lines()
        .take_while(|line| line.starts_with("        "))
        .map(str::trim)
        .filter(|line| !line.is_empty())
        .collect();
    assert_eq!(commands.len(), 2, "the step must sync and check the lock");

    let tmp = tempfile::tempdir().expect("temp dir");
    let root = tmp.path();
    fixture(root, "9.9.9", "1.0.0");
    // Destination is the script's own repo-relative path, so a moved script
    // no longer satisfies a stale documented path.
    let script_dest = root.join(
        script()
            .strip_prefix(env!("CARGO_MANIFEST_DIR"))
            .expect("script lives under the repo"),
    );
    fs::create_dir_all(script_dest.parent().expect("script parent")).expect("create script dir");
    fs::copy(script(), &script_dest).expect("copy script");
    for (index, command) in commands.iter().enumerate() {
        let mut words = command.split_whitespace();
        let executable = words.next().expect("command must not be empty");
        let output = Command::new(root.join(executable))
            .args(words)
            .current_dir(root)
            .env("CARGO_NET_OFFLINE", "true")
            .env("CARGO_TARGET_DIR", root.join("target"))
            .stdin(Stdio::null())
            .output()
            .expect("run documented lockfile command");
        assert!(
            output.status.success(),
            "documented command {command:?} failed: {}",
            String::from_utf8_lossy(&output.stderr)
        );
        if index == 0 {
            assert_eq!(
                read_lock(root),
                lock_text("9.9.9"),
                "first command must restamp the stale lock"
            );
        } else {
            assert!(
                String::from_utf8_lossy(&output.stdout).contains("OK"),
                "second command must check the lock"
            );
        }
    }
}
