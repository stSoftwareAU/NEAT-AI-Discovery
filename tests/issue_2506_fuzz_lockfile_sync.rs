//! Issue #2506: `fuzz/Cargo.lock` must not keep a stale version for the path
//! dependency `neat_ai_discovery`, or `cargo fuzz run --locked` fails.
//!
//! The fuzz crate depends on the root crate by path (`path = ".."`), so Cargo
//! records the root package and its version in `fuzz/Cargo.lock`. Every root
//! version bump left that line behind. `quality/fuzz_lockfile.sh` keeps it in
//! step: `sync` rewrites only that package's `version = "..."` line to the root
//! `Cargo.toml` version, and `check` runs `cargo metadata --locked` against the
//! fuzz manifest and fails loudly when the lock is stale. `quality.sh` runs
//! `sync` then `check` before `cargo deny`.
//!
//! The script tests build their fixtures inside `tempfile::tempdir()`. The
//! quality-gate test runs copies of the gate and its helpers in a private root.

use std::fs;
use std::os::unix::fs::PermissionsExt;
use std::path::{Path, PathBuf};
use std::process::{Command, Output, Stdio};

fn copy_quality_gate(root: &Path) {
    let repo = Path::new(env!("CARGO_MANIFEST_DIR"));
    for rel in [
        "quality.sh",
        "quality/bash_syntax.sh",
        "quality/shellcheck.sh",
        "quality/cargo_install_pinning.sh",
        "quality/fuzz_lockfile.sh",
        "scripts/check-pr-summary-location.sh",
    ] {
        let dest = root.join(rel);
        fs::create_dir_all(dest.parent().expect("parent")).expect("create fixture dir");
        fs::copy(repo.join(rel), dest).expect("copy gate script");
    }
    fs::create_dir_all(root.join("docs")).expect("create docs");
}

/// Write an executable stub script into `dir`.
fn write_stub(dir: &Path, name: &str, body: &str) {
    let path = dir.join(name);
    fs::write(&path, body).expect("write stub");
    let mut perms = fs::metadata(&path).expect("stat stub").permissions();
    perms.set_mode(0o755);
    fs::set_permissions(&path, perms).expect("chmod stub");
}

/// Absolute path to the script under test.
fn script() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("quality/fuzz_lockfile.sh")
}

/// Fuzz manifest matching the shape of the real `fuzz/Cargo.toml`.
const FUZZ_MANIFEST: &str = r#"[package]
name = "neat-ai-discovery-fuzz"
version = "0.0.0"
edition = "2021"
publish = false

[lib]
path = "src/lib.rs"

[dependencies.neat_ai_discovery]
path = ".."

[workspace]
members = ["."]
"#;

/// `fuzz/Cargo.lock` in cargo's `version = 4` format, with the path package
/// `neat_ai_discovery` at `locked_version`. Verified against the installed cargo
/// with `cargo metadata --locked` (accepted when versions match, rejected when not).
fn lock_text(locked_version: &str) -> String {
    format!(
        r#"# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "neat-ai-discovery-fuzz"
version = "0.0.0"
dependencies = [
 "neat_ai_discovery",
]

[[package]]
name = "neat_ai_discovery"
version = "{locked_version}"
"#
    )
}

/// Registry packages that share the stale version string. Sync must leave them
/// alone, and the name `neat_ai_discovery_extra` checks for prefix matching.
const REGISTRY_PACKAGES: &str = r#"
[[package]]
name = "neat_ai_discovery_extra"
version = "1.2.3"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "abababababababababababababababababababababababababababababababab"

[[package]]
name = "other"
version = "1.2.3"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "abababababababababababababababababababababababababababababababab"
"#;

/// Build a fuzz crate that depends on the root crate by path. The root is at
/// `crate_version`, and the fuzz lock records the path package at `locked_version`.
fn fixture(root: &Path, crate_version: &str, locked_version: &str) {
    fs::create_dir_all(root.join("src")).expect("create root src");
    fs::create_dir_all(root.join("fuzz/src")).expect("create fuzz src");
    fs::write(
        root.join("Cargo.toml"),
        format!(
            "[package]\nname = \"neat_ai_discovery\"\nversion = \"{crate_version}\"\nedition = \"2021\"\n"
        ),
    )
    .expect("write root Cargo.toml");
    fs::write(root.join("src/lib.rs"), "").expect("write root lib.rs");
    fs::write(root.join("fuzz/Cargo.toml"), FUZZ_MANIFEST).expect("write fuzz Cargo.toml");
    fs::write(root.join("fuzz/src/lib.rs"), "").expect("write fuzz lib.rs");
    fs::write(root.join("fuzz/Cargo.lock"), lock_text(locked_version))
        .expect("write fuzz Cargo.lock");
}

fn read_lock(root: &Path) -> String {
    fs::read_to_string(root.join("fuzz/Cargo.lock")).expect("read fuzz/Cargo.lock")
}

/// Run `quality/fuzz_lockfile.sh <mode> <root>` with stdin closed. Cargo runs
/// offline with its target directory inside the temp root.
fn run_script(mode: &str, root: &Path) -> Output {
    Command::new("bash")
        .arg(script())
        .arg(mode)
        .arg(root)
        .env("CARGO_NET_OFFLINE", "true")
        .env("CARGO_TARGET_DIR", root.join("target"))
        .stdin(Stdio::null())
        .output()
        .expect("run quality/fuzz_lockfile.sh")
}

#[test]
fn concurrent_syncs_preserve_the_lock_and_its_mode() {
    let tmp = tempfile::tempdir().expect("temp dir");
    let root = tmp.path();
    fixture(root, "1.2.4", "1.2.3");
    let lock = root.join("fuzz/Cargo.lock");
    fs::set_permissions(&lock, fs::Permissions::from_mode(0o640)).expect("chmod lock");
    let mut children: Vec<_> = (0..16)
        .map(|_| {
            Command::new("bash")
                .arg(script())
                .arg("sync")
                .arg(root)
                .spawn()
                .expect("start sync")
        })
        .collect();
    for child in &mut children {
        assert!(child.wait().expect("wait for sync").success());
    }
    assert_eq!(read_lock(root), lock_text("1.2.4"));
    assert_eq!(
        fs::metadata(lock).expect("stat lock").permissions().mode() & 0o777,
        0o640
    );
}

#[test]
fn sync_restamps_only_the_path_package_version() {
    let tmp = tempfile::tempdir().expect("temp dir");
    let root = tmp.path();
    fixture(root, "1.2.4", "1.2.3");
    fs::write(
        root.join("fuzz/Cargo.lock"),
        format!("{}{REGISTRY_PACKAGES}", lock_text("1.2.3")),
    )
    .expect("write lock with registry packages");

    let output = run_script("sync", root);

    assert!(
        output.status.success(),
        "sync must succeed on a stale lock (Issue #2506)\nstdout:\n{}\nstderr:\n{}",
        String::from_utf8_lossy(&output.stdout),
        String::from_utf8_lossy(&output.stderr)
    );
    assert_eq!(
        read_lock(root),
        format!("{}{REGISTRY_PACKAGES}", lock_text("1.2.4")),
        "sync must rewrite only the neat_ai_discovery version line (Issue #2506)"
    );
}

#[test]
fn sync_is_a_no_op_when_already_current() {
    let tmp = tempfile::tempdir().expect("temp dir");
    let root = tmp.path();
    fixture(root, "1.2.4", "1.2.4");
    let before = read_lock(root);

    let output = run_script("sync", root);

    assert!(
        output.status.success(),
        "sync must succeed on a current lock (Issue #2506)\nstderr:\n{}",
        String::from_utf8_lossy(&output.stderr)
    );
    assert_eq!(
        read_lock(root),
        before,
        "sync must leave a current lock byte-identical (Issue #2506)"
    );
}

#[test]
fn sync_fails_loud_when_the_path_package_is_missing() {
    let tmp = tempfile::tempdir().expect("temp dir");
    let root = tmp.path();
    fixture(root, "1.2.4", "1.2.4");
    fs::write(
        root.join("fuzz/Cargo.lock"),
        r#"# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "neat-ai-discovery-fuzz"
version = "0.0.0"
"#,
    )
    .expect("write lock without the path package");
    let before = read_lock(root);

    let output = run_script("sync", root);

    assert!(
        !output.status.success(),
        "sync must fail when the path package is absent (Issue #2506)"
    );
    let stderr = String::from_utf8_lossy(&output.stderr);
    assert!(
        stderr.contains("neat_ai_discovery") && stderr.contains("Cargo.lock"),
        "stderr must name the crate and the lock file (Issue #2506), got:\n{stderr}"
    );
    assert_eq!(
        read_lock(root),
        before,
        "a failed sync must leave the lock untouched (Issue #2506)"
    );
}

#[test]
fn check_rejects_a_stale_lock_then_accepts_it_after_sync() {
    let tmp = tempfile::tempdir().expect("temp dir");
    let root = tmp.path();
    fixture(root, "1.2.4", "1.2.3");

    let stale = run_script("check", root);

    assert!(
        !stale.status.success(),
        "check must reject a stale fuzz lock (Issue #2506)"
    );
    let stderr = String::from_utf8_lossy(&stale.stderr);
    assert!(
        stderr.contains("run quality/fuzz_lockfile.sh sync"),
        "check must tell the operator how to fix a stale lock (Issue #2506), got:\n{stderr}"
    );
    assert!(
        stderr.contains("--locked"),
        "check must surface cargo's cause line naming --locked (Issue #2506), got:\n{stderr}"
    );

    let synced = run_script("sync", root);
    assert!(
        synced.status.success(),
        "sync must repair the stale lock (Issue #2506)\nstderr:\n{}",
        String::from_utf8_lossy(&synced.stderr)
    );

    // Positive control: the same fixture now passes once only the lock version differs.
    let fresh = run_script("check", root);
    assert!(
        fresh.status.success(),
        "check must accept the lock after sync (Issue #2506)\nstdout:\n{}\nstderr:\n{}",
        String::from_utf8_lossy(&fresh.stdout),
        String::from_utf8_lossy(&fresh.stderr)
    );
}

